#!/usr/bin/env node
// Writes the open-source notices Mood Read ships (design/system/DECISION.md, Iconography: 06.1's rights check),
// word for word from each installed package's license file, into the two places they are shown:
//   src/ui/licenses.ts    the in-app /licenses screen reads it
//   public/licenses.txt   served with the web build at /licenses.txt
// Run after installing or upgrading one of these packages: `node scripts/licenses.mjs`.
// src/lib/licenses.test.ts fails while either file differs from what this writes.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/** What ships, in the order it is shown. `file` is the license file, under node_modules/. */
export const SOURCES = [
  {
    id: 'lucide',
    name: 'Lucide icons',
    package: 'lucide-react-native',
    license: 'ISC; the icons derived from Feather, MIT',
    file: 'lucide-react-native/LICENSE',
  },
  {
    id: 'react-native-svg',
    name: 'react-native-svg',
    package: 'react-native-svg',
    license: 'MIT',
    file: 'react-native-svg/LICENSE',
  },
  {
    id: 'bricolage-grotesque',
    name: 'Bricolage Grotesque (the display font)',
    package: '@expo-google-fonts/bricolage-grotesque',
    license: 'SIL Open Font License 1.1',
    file: '@expo-google-fonts/bricolage-grotesque/LICENSE_FONT',
  },
];

const read = (file) => readFileSync(path.join(ROOT, 'node_modules', file), 'utf8').replace(/\r\n/g, '\n');

const version = (pkg) =>
  JSON.parse(readFileSync(path.join(ROOT, 'node_modules', pkg, 'package.json'), 'utf8')).version;

export function notices() {
  return SOURCES.map((s) => ({ ...s, version: version(s.package), text: read(s.file) }));
}

export function sourceFile(list) {
  const body = list
    .map(
      (n) => `  {
    id: ${JSON.stringify(n.id)},
    name: ${JSON.stringify(n.name)},
    package: ${JSON.stringify(n.package)},
    version: ${JSON.stringify(n.version)},
    license: ${JSON.stringify(n.license)},
    file: ${JSON.stringify(n.file)},
    text: ${JSON.stringify(n.text)},
  },`,
    )
    .join('\n');
  return `// Generated by scripts/licenses.mjs from each package's license file, word for word. Do not edit by hand: run
// \`node scripts/licenses.mjs\` after an install or upgrade (src/lib/licenses.test.ts fails until you do).
// The in-app /licenses screen shows these, and public/licenses.txt carries the same text to the web build.

export type Notice = {
  id: string;
  name: string;
  package: string;
  version: string;
  license: string;
  /** The license file it was copied from, under node_modules/. */
  file: string;
  text: string;
};

export const NOTICES: readonly Notice[] = [
${body}
];
`;
}

export function textFile(list) {
  const rule = '='.repeat(72);
  const head = [
    'Mood Read: open-source notices',
    '',
    'Mood Read is built with the open-source work below. Each notice is its license, word for word,',
    'copied from the package it ships in.',
  ].join('\n');
  const parts = list.map((n) =>
    [rule, `${n.name}: ${n.package} ${n.version} (${n.license})`, rule, '', n.text.trimEnd()].join('\n'),
  );
  return `${[head, ...parts].join('\n\n')}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const list = notices();
  writeFileSync(path.join(ROOT, 'src/ui/licenses.ts'), sourceFile(list));
  writeFileSync(path.join(ROOT, 'public/licenses.txt'), textFile(list));
  console.log(`licenses: ${list.length} notices written to src/ui/licenses.ts and public/licenses.txt`);
}
